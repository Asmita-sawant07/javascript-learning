//Calculator functions
function add(a, b) {
  return a + b;
}
function mul(a, b) {
  return a * b;
}
function sub(a, b) {
  return a - b;
}
function div(a, b) {
  return a / b;
}
console.log(add(20, 5)); 
console.log(mul(20, 5)); 
console.log(sub(20, 5)); 
console.log(div(20, 5)); 
//Even or odd
const isEven = (num) => num % 2 === 0;
console.log(isEven(8));
console.log(isEven(13));
console.log(isEven(0));